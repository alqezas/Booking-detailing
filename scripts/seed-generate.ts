/**
 * pnpm seed:generate — writes supabase/seed.sql for local development and tests.
 *
 * Demo studios come from tenants/<slug>/business.json through the same
 * svc_sync_tenant() the publish pipeline uses, then get flagged demo bookings.
 * Business names therefore live only in tenants/ and the generated seed,
 * never in src/.
 *
 * Local demo owners (one per studio) sign in with the password in
 * DEMO_OWNER_PASSWORD below. Local seed only — never pushed to production.
 */
import {createHash} from 'node:crypto';
import {writeFileSync} from 'node:fs';
import path from 'node:path';
import {toSyncPayload} from './lib/payload.ts';
import {ROOT, isLoaded, listTenantSlugs, loadTenant, printIssues} from './lib/tenants.ts';

import {DEMO_OWNER_PASSWORD} from './lib/demo.ts';

const sqlString = (s: string) => `'${s.replace(/'/g, "''")}'`;
const userId = (slug: string) => {
  const h = createHash('sha256').update(`demo-owner:${slug}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
};

const parts: string[] = [
  '-- GENERATED by `pnpm seed:generate` from tenants/*/business.json. Do not edit by hand.',
  '-- Local development and tests only.',
  '',
];

for (const slug of listTenantSlugs()) {
  const t = await loadTenant(slug);
  if (!isLoaded(t)) {
    printIssues(slug, t.issues);
    process.exit(1);
  }
  const payload = JSON.stringify(toSyncPayload(t.config));
  const id = userId(slug);
  parts.push(
    `-- ${t.config.name}`,
    `select public.svc_sync_tenant(${sqlString(payload)}::jsonb, ${sqlString(t.hash)}, true);`,
    `select public.svc_seed_demo_bookings(${sqlString(slug)});`,
    `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, email_change,
  email_change_token_new, recovery_token)
values ('00000000-0000-0000-0000-000000000000', '${id}', 'authenticated', 'authenticated', ${sqlString(t.config.owner.email)},
  extensions.crypt(${sqlString(DEMO_OWNER_PASSWORD)}, extensions.gen_salt('bf')), now(),
  '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '')
on conflict (id) do nothing;`,
    `insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values ('${id}', '${id}', '${id}', jsonb_build_object('sub', '${id}', 'email', ${sqlString(t.config.owner.email)}, 'email_verified', true),
  'email', now(), now(), now())
on conflict do nothing;`,
    `select public.svc_add_member(${sqlString(slug)}, '${id}', 'owner');`,
    '',
  );
}

const out = path.join(ROOT, 'supabase', 'seed.sql');
writeFileSync(out, parts.join('\n'), 'utf8');
console.log(`✓ ${path.relative(ROOT, out)}: ${listTenantSlugs().length} студии`);
