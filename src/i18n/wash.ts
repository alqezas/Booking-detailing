const CATALOGUES: Record<string, WashMessages> = {ru, cs, pl, uk};
export const washMsg = (): WashMessages => CATALOGUES[msg.lang] ?? ru;

/** Short weekday names in the studio language, ISO order (Monday first). */
export const weekdayShort = (): string[] =>
  Array.from({length: 7}, (_, i) => new Date(Date.UTC(2024, 0, 1 + i)).toLocaleDateString(msg.intl, {weekday: 'short', timeZone: 'UTC'}));

/** «Po, St, Pá» / «Po–Pá» for a rule's ISO weekdays. */
export function daysLabel(days: number[]): string {
  const names = weekdayShort();
  const sorted = [...new Set(days)].sort();
  const contiguous = sorted.length > 2 && sorted.every((d, i) => i === 0 || d === sorted[i - 1]! + 1);
  return contiguous ? `${names[sorted[0]! - 1]}–${names[sorted.at(-1)! - 1]}` : sorted.map(d => names[d - 1]).join(', ');
}
