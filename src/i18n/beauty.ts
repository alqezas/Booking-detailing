const CATALOGUES = {ru, uk, cs, pl, de};

const barberCache = new Map<string, BeautyMessages>();
export const beautyMsg = (): BeautyMessages => {
  if (vocabulary !== 'barber') return CATALOGUES[msg.lang];
  let m = barberCache.get(msg.lang);
  if (!m) barberCache.set(msg.lang, (m = mergeMessages(CATALOGUES[msg.lang], BARBER_BEAUTY[msg.lang])));
  return m;
};
