/** Deep merge for plain objects; functions, arrays and primitives replace. */
export function mergeMessages<T>(base: T, over: unknown): T {
  if (!over || typeof over !== 'object' || Array.isArray(over)) return (over ?? base) as T;
  const out: Record<string, unknown> = {...(base as Record<string, unknown>)};
  for (const [k, v] of Object.entries(over as Record<string, unknown>)) {
    const b = out[k];
    out[k] = b && typeof b === 'object' && !Array.isArray(b) && v && typeof v === 'object' && !Array.isArray(v) ? mergeMessages(b, v) : v;
  }
  return out as T;
}
